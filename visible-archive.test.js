import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';

test('automatic archive is visible, exportable, and persisted by the Windows launcher', async () => {
  const app=await readFile(new URL('../src/ui/App.tsx',import.meta.url),'utf8');
  const server=await readFile(new URL('../start-static.ps1',import.meta.url),'utf8');
  const ignore=await readFile(new URL('../.gitignore',import.meta.url),'utf8');
  assert.match(app,/Recent itineraries/);
  assert.match(app,/daytrip-\$\{fileCity\}-\$\{trip\.itinerary\.date\}\.json/);
  assert.match(app,/CALCULATED FIT SCORE/);
  assert.match(app,/MINIMUM PASS MARK/);
  assert.match(app,/CALCULATED FIT SCORE:/);
  assert.match(server,/daytrip-data\/itinerary-archive\.json/);
  assert.match(server,/Save-AutoGeneratedPlan \$p \$body/);
  assert.match(server,/archivePersisted=\$true/);
  assert.match(ignore,/daytrip-data\//);
});
